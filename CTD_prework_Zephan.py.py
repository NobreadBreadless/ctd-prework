# Determines if person can ride rollercoaster based on their height
# Asks for name and height

name = input("What's your name?")
height = int(input("How tall are you? (in inches)"))

if height < 48:
  print(f"Sup {name}, since you are {height} inches tall, you cannot ride this rollercoaster. You're too short.")

elif height >= 48 and height <= 84:
  print(f"Sup {name}, since you are {height} inches tall, you may ride this rollercoaster.")

else:
  print("Dang you tall! You can't ride this rollercoaster tho; you might get your head chopped off:)")

